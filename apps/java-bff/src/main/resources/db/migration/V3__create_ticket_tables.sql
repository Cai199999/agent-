-- V3: 工单核心、事件时间线、派单与挂起

CREATE TABLE ticket (
    id BIGINT NOT NULL COMMENT '主键，雪花 ID',
    tenant_id BIGINT NOT NULL DEFAULT 0 COMMENT '租户 ID',
    ticket_no VARCHAR(32) NOT NULL COMMENT '业务单号，租户内唯一',
    title VARCHAR(200) NOT NULL COMMENT '标题',
    description TEXT NULL COMMENT '详细描述',
    ticket_type_code VARCHAR(32) NOT NULL COMMENT '工单类型编码',
    priority_code VARCHAR(16) NOT NULL DEFAULT 'NORMAL' COMMENT '优先级编码',
    status_code VARCHAR(32) NOT NULL DEFAULT 'PENDING' COMMENT '当前状态编码',
    source_code VARCHAR(16) NOT NULL DEFAULT 'FORM' COMMENT 'FORM/CHAT/PHONE/INSPECTION/AGENT',
    source_ref_type VARCHAR(32) NULL COMMENT 'CHAT_SESSION/CHAT_MESSAGE/TOOL_CALL/INSPECTION/PHONE/MANUAL',
    source_ref_id BIGINT NULL COMMENT '来源对象 ID',
    triage_id BIGINT NULL COMMENT '分诊记录 ID',
    reporter_id BIGINT NOT NULL COMMENT '报障人 ID',
    reporter_dept_id BIGINT NULL COMMENT '报障人部门 ID',
    assignee_id BIGINT NULL COMMENT '当前处理人 ID',
    assignee_dept_id BIGINT NULL COMMENT '当前处理部门 ID',
    customer_id BIGINT NULL COMMENT '关联业户 ID（逻辑外键）',
    room_id BIGINT NULL COMMENT '关联房号 ID（逻辑外键）',
    equipment_id BIGINT NULL COMMENT '关联设备 ID（逻辑外键）',
    location_text VARCHAR(255) NULL COMMENT '位置描述',
    sla_policy_id BIGINT NULL COMMENT 'SLA 策略 ID',
    sla_response_due_at DATETIME(3) NULL COMMENT '首次响应到期时间（快照）',
    sla_resolve_due_at DATETIME(3) NULL COMMENT '解决到期时间（快照）',
    sla_response_breached TINYINT(1) NOT NULL DEFAULT 0 COMMENT '首次响应是否超时（快照）',
    sla_resolve_breached TINYINT(1) NOT NULL DEFAULT 0 COMMENT '解决是否超时（快照）',
    hold_started_at DATETIME(3) NULL COMMENT '当前挂起开始时间',
    hold_reason VARCHAR(500) NULL COMMENT '当前/最近挂起原因',
    hold_minutes INT NOT NULL DEFAULT 0 COMMENT '累计挂起时长（分钟）',
    first_response_at DATETIME(3) NULL COMMENT '首次响应时间',
    accepted_at DATETIME(3) NULL COMMENT '接单时间',
    resolved_at DATETIME(3) NULL COMMENT '提交解决时间',
    closed_at DATETIME(3) NULL COMMENT '关闭时间',
    close_reason_code VARCHAR(32) NULL COMMENT '关闭原因编码',
    cancel_reason VARCHAR(500) NULL COMMENT '取消原因',
    satisfaction_score TINYINT NULL COMMENT '满意度 1-5（P1）',
    satisfaction_comment VARCHAR(1000) NULL COMMENT '满意度评价（P1）',
    rated_by BIGINT NULL COMMENT '评价人（P1）',
    satisfaction_at DATETIME(3) NULL COMMENT '评价时间（P1）',
    version INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本号',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间（UTC）',
    created_by BIGINT NULL COMMENT '创建人 ID',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间（UTC）',
    updated_by BIGINT NULL COMMENT '更新人 ID',
    deleted_at DATETIME(3) NULL COMMENT '软删除时间（UTC）',
    deleted_by BIGINT NULL COMMENT '删除人 ID',
    PRIMARY KEY (id),
    UNIQUE KEY uk_ticket_tenant_no (tenant_id, ticket_no),
    KEY idx_ticket_status_deleted_updated (status_code, deleted_at, updated_at),
    KEY idx_ticket_assignee_status (assignee_id, status_code, deleted_at),
    KEY idx_ticket_reporter_created (reporter_id, created_at),
    KEY idx_ticket_customer (customer_id),
    KEY idx_ticket_room (room_id),
    KEY idx_ticket_equipment (equipment_id),
    KEY idx_ticket_created (created_at),
    KEY idx_ticket_sla_due (status_code, sla_resolve_due_at),
    KEY idx_ticket_source_ref (source_ref_type, source_ref_id),
    KEY idx_ticket_triage (triage_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='工单主表';

CREATE TABLE ticket_event (
    id BIGINT NOT NULL COMMENT '主键',
    tenant_id BIGINT NOT NULL DEFAULT 0 COMMENT '租户 ID',
    ticket_id BIGINT NOT NULL COMMENT '工单 ID',
    event_type VARCHAR(32) NOT NULL COMMENT '事件类型',
    from_status VARCHAR(32) NULL COMMENT '变更前状态',
    to_status VARCHAR(32) NULL COMMENT '变更后状态',
    operator_id BIGINT NULL COMMENT '操作人',
    operator_role VARCHAR(32) NULL COMMENT '操作人角色',
    reason VARCHAR(500) NULL COMMENT '原因/备注',
    payload_json JSON NULL COMMENT '扩展信息',
    trace_id VARCHAR(64) NULL COMMENT '追踪 ID',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间（UTC）',
    created_by BIGINT NULL COMMENT '操作人 ID',
    PRIMARY KEY (id),
    KEY idx_ticket_event_ticket (ticket_id, id),
    KEY idx_ticket_event_trace (trace_id),
    KEY idx_ticket_event_type (event_type, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='工单事件时间线';

CREATE TABLE ticket_comment (
    id BIGINT NOT NULL COMMENT '主键',
    tenant_id BIGINT NOT NULL DEFAULT 0 COMMENT '租户 ID',
    ticket_id BIGINT NOT NULL COMMENT '工单 ID',
    parent_id BIGINT NULL COMMENT '父评论 ID',
    author_id BIGINT NOT NULL COMMENT '作者 ID',
    visibility VARCHAR(16) NOT NULL DEFAULT 'PUBLIC' COMMENT 'PUBLIC/INTERNAL',
    content TEXT NOT NULL COMMENT '评论内容',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间（UTC）',
    created_by BIGINT NULL COMMENT '创建人 ID',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间（UTC）',
    updated_by BIGINT NULL COMMENT '更新人 ID',
    deleted_at DATETIME(3) NULL COMMENT '软删除时间（UTC）',
    deleted_by BIGINT NULL COMMENT '删除人 ID',
    PRIMARY KEY (id),
    KEY idx_ticket_comment_ticket (ticket_id, id),
    KEY idx_ticket_comment_parent (parent_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='工单评论表';

CREATE TABLE ticket_attachment (
    id BIGINT NOT NULL COMMENT '主键',
    tenant_id BIGINT NOT NULL DEFAULT 0 COMMENT '租户 ID',
    ticket_id BIGINT NOT NULL COMMENT '工单 ID',
    comment_id BIGINT NULL COMMENT '关联评论 ID',
    file_id BIGINT NOT NULL COMMENT '文件对象 ID',
    attachment_type VARCHAR(32) NOT NULL DEFAULT 'GENERAL' COMMENT '附件类型',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间（UTC）',
    created_by BIGINT NULL COMMENT '创建人 ID',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间（UTC）',
    updated_by BIGINT NULL COMMENT '更新人 ID',
    deleted_at DATETIME(3) NULL COMMENT '软删除时间（UTC）',
    deleted_by BIGINT NULL COMMENT '删除人 ID',
    PRIMARY KEY (id),
    KEY idx_ticket_attachment_ticket (ticket_id),
    KEY idx_ticket_attachment_file (file_id),
    KEY idx_ticket_attachment_comment (comment_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='工单附件表';

CREATE TABLE ticket_assignment (
    id BIGINT NOT NULL COMMENT '主键',
    tenant_id BIGINT NOT NULL DEFAULT 0 COMMENT '租户 ID',
    ticket_id BIGINT NOT NULL COMMENT '工单 ID',
    action_type VARCHAR(32) NOT NULL COMMENT 'ASSIGN/CLAIM/TRANSFER/TRANSFER_DEPT/RELEASE/REJECT',
    from_assignee_id BIGINT NULL COMMENT '原处理人',
    to_assignee_id BIGINT NULL COMMENT '新处理人',
    from_dept_id BIGINT NULL COMMENT '原部门',
    to_dept_id BIGINT NULL COMMENT '新部门',
    operated_by BIGINT NOT NULL COMMENT '操作人',
    reason VARCHAR(500) NULL COMMENT '原因',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间（UTC）',
    created_by BIGINT NULL COMMENT '操作人 ID',
    PRIMARY KEY (id),
    KEY idx_ticket_assignment_ticket (ticket_id, id),
    KEY idx_ticket_assignment_assignee (to_assignee_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='工单派单/认领历史';

CREATE TABLE ticket_claim_pool (
    id BIGINT NOT NULL COMMENT '主键',
    tenant_id BIGINT NOT NULL DEFAULT 0 COMMENT '租户 ID',
    ticket_id BIGINT NOT NULL COMMENT '工单 ID，唯一',
    status VARCHAR(16) NOT NULL DEFAULT 'OPEN' COMMENT 'OPEN/CLAIMED/EXPIRED/CANCELLED',
    entered_at DATETIME(3) NOT NULL COMMENT '进入池时间',
    expires_at DATETIME(3) NULL COMMENT '过期时间',
    claimed_by BIGINT NULL COMMENT '认领人',
    claimed_at DATETIME(3) NULL COMMENT '认领时间',
    version INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本号',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间（UTC）',
    created_by BIGINT NULL COMMENT '创建人 ID',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间（UTC）',
    updated_by BIGINT NULL COMMENT '更新人 ID',
    deleted_at DATETIME(3) NULL COMMENT '软删除时间（UTC）',
    deleted_by BIGINT NULL COMMENT '删除人 ID',
    PRIMARY KEY (id),
    UNIQUE KEY uk_ticket_claim_pool_ticket (tenant_id, ticket_id),
    KEY idx_ticket_claim_pool_status (status, expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='抢单池';

CREATE TABLE ticket_hold (
    id BIGINT NOT NULL COMMENT '主键',
    tenant_id BIGINT NOT NULL DEFAULT 0 COMMENT '租户 ID',
    ticket_id BIGINT NOT NULL COMMENT '工单 ID',
    started_at DATETIME(3) NOT NULL COMMENT '挂起开始时间（UTC）',
    ended_at DATETIME(3) NULL COMMENT '挂起结束时间；NULL 表示当前仍在挂起',
    reason VARCHAR(500) NULL COMMENT '挂起原因',
    started_by BIGINT NULL COMMENT '挂起操作人',
    ended_by BIGINT NULL COMMENT '恢复操作人',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间（UTC）',
    created_by BIGINT NULL COMMENT '操作人 ID',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间（UTC）',
    PRIMARY KEY (id),
    KEY idx_ticket_hold_ticket (ticket_id, started_at),
    KEY idx_ticket_hold_open (ended_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='工单挂起区间';

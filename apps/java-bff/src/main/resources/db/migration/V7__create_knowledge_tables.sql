-- V7: 知识库元数据、分块与向量映射（MVP 同步入库）

CREATE TABLE kb_doc (
    id BIGINT NOT NULL COMMENT '主键',
    tenant_id BIGINT NOT NULL DEFAULT 0 COMMENT '租户 ID',
    doc_no VARCHAR(32) NOT NULL COMMENT '文档业务号',
    title VARCHAR(200) NOT NULL COMMENT '标题',
    category_code VARCHAR(64) NOT NULL COMMENT '知识分类',
    source_type VARCHAR(16) NOT NULL DEFAULT 'UPLOAD' COMMENT 'UPLOAD/MANUAL/TICKET',
    source_ref_id BIGINT NULL COMMENT '来源对象 ID',
    file_id BIGINT NULL COMMENT '原始文件 ID',
    visibility_type VARCHAR(16) NOT NULL DEFAULT 'PUBLIC' COMMENT '粗分类快照',
    status VARCHAR(16) NOT NULL DEFAULT 'INDEXING' COMMENT 'UPLOADED/PARSING/INDEXING/ACTIVE/FAILED/DISABLED',
    current_version INT NOT NULL DEFAULT 1 COMMENT '当前版本号',
    chunk_count INT NOT NULL DEFAULT 0 COMMENT '分块数量',
    embedding_model VARCHAR(100) NULL COMMENT 'Embedding 模型',
    embedding_dim INT NULL COMMENT '向量维度',
    vector_collection VARCHAR(64) NULL COMMENT 'Milvus collection',
    index_version INT NULL COMMENT '已生效索引版本',
    checksum VARCHAR(64) NULL COMMENT '文件 SHA-256',
    error_message VARCHAR(1000) NULL COMMENT '失败原因',
    version INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本号',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间（UTC）',
    created_by BIGINT NULL COMMENT '创建人 ID',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间（UTC）',
    updated_by BIGINT NULL COMMENT '更新人 ID',
    deleted_at DATETIME(3) NULL COMMENT '软删除时间（UTC）',
    deleted_by BIGINT NULL COMMENT '删除人 ID',
    PRIMARY KEY (id),
    UNIQUE KEY uk_kb_doc_tenant_no (tenant_id, doc_no),
    KEY idx_kb_doc_category (category_code, status, deleted_at),
    KEY idx_kb_doc_source (source_type, source_ref_id),
    KEY idx_kb_doc_status (status, updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='知识文档';

CREATE TABLE kb_chunk (
    id BIGINT NOT NULL COMMENT '主键',
    tenant_id BIGINT NOT NULL DEFAULT 0 COMMENT '租户 ID',
    doc_id BIGINT NOT NULL COMMENT '文档 ID',
    doc_version INT NOT NULL COMMENT '文档版本号',
    chunk_no INT NOT NULL COMMENT '分块序号',
    content MEDIUMTEXT NOT NULL COMMENT '分块文本',
    token_count INT NULL COMMENT 'token 数',
    vector_id VARCHAR(128) NOT NULL COMMENT '派生 Milvus 主键',
    vector_collection VARCHAR(64) NOT NULL COMMENT 'Milvus collection',
    metadata_json JSON NULL COMMENT '额外过滤元数据',
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' COMMENT 'PENDING/ACTIVE/FAILED/DELETED',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间（UTC）',
    created_by BIGINT NULL COMMENT '创建人 ID',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间（UTC）',
    updated_by BIGINT NULL COMMENT '更新人 ID',
    deleted_at DATETIME(3) NULL COMMENT '软删除时间（UTC）',
    deleted_by BIGINT NULL COMMENT '删除人 ID',
    PRIMARY KEY (id),
    UNIQUE KEY uk_kb_chunk_doc (tenant_id, doc_id, doc_version, chunk_no),
    KEY idx_kb_chunk_vector (vector_collection, vector_id),
    KEY idx_kb_chunk_doc_status (doc_id, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='知识分块';

CREATE TABLE vector_object (
    id BIGINT NOT NULL COMMENT '主键',
    tenant_id BIGINT NOT NULL DEFAULT 0 COMMENT '租户 ID',
    object_type VARCHAR(16) NOT NULL COMMENT 'KB_CHUNK/TICKET',
    object_id BIGINT NOT NULL COMMENT '源对象 ID',
    object_version INT NOT NULL COMMENT '源对象版本',
    seq_no INT NOT NULL DEFAULT 0 COMMENT '对象内序号',
    vector_id VARCHAR(128) NOT NULL COMMENT 'Milvus 主键',
    vector_collection VARCHAR(64) NOT NULL COMMENT 'Milvus collection',
    content_hash VARCHAR(64) NULL COMMENT '内容 SHA-256',
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/ACTIVE/FAILED/DELETED',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间（UTC）',
    created_by BIGINT NULL COMMENT '创建人 ID',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间（UTC）',
    updated_by BIGINT NULL COMMENT '更新人 ID',
    deleted_at DATETIME(3) NULL COMMENT '软删除时间（UTC）',
    deleted_by BIGINT NULL COMMENT '删除人 ID',
    PRIMARY KEY (id),
    UNIQUE KEY uk_vector_object_vector (tenant_id, object_type, vector_collection, vector_id),
    UNIQUE KEY uk_vector_object_source (tenant_id, object_type, object_id, object_version, seq_no),
    KEY idx_vector_object_scan (object_type, status),
    KEY idx_vector_object_source_query (object_type, object_id, object_version)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='向量对象映射';
